import { readFile, rm, stat } from "node:fs/promises";
import { summarizeChange } from "../../change.ts";
import { resolveInRoot } from "../../paths.ts";
import { objectSchema, type ToolDef } from "../../types.ts";

/** `deleteFile`: removes one file. Change summary: the file with all its lines counted as removed (diff when small). */
export const deleteFile: ToolDef = {
  name: "deleteFile",
  description: "Delete a file. Fails for missing paths and directories. Returns a change summary with the removed lines.",
  parameters: objectSchema({ path: { type: "string", description: "File path, relative to the workspace root." } }, ["path"]),
  returns: "{ files: { path: string; added: number; removed: number }[]; diff?: string }",
  meta: {
    whenToUse: "Remove a file that is obsolete, generated by mistake or replaced by another.",
    whenNotToUse: "Not for undoing edits to a tracked file (use restore) or for moving a file (use moveFile).",
    examples: ["delete the unused helper module", "remove a stray backup file"],
    category: "fs",
    effect: "write",
    requires: [],
    cost: 1,
  },
  async fn(args: { path: string }, ctx) {
    const abs = resolveInRoot(ctx.root, args.path);
    const st = await stat(abs).catch((e: NodeJS.ErrnoException) => {
      if (e.code === "ENOENT") throw new Error(`no such file: ${args.path}`);
      throw e;
    });
    if (!st.isFile()) throw new Error(`not a file: ${args.path}`);
    const before = await readFile(abs, "utf8");
    await rm(abs);
    return summarizeChange(ctx.root, abs, before, "");
  },
};
